#!/usr/bin/env node
/**
 * Packs the isometric facility tiles into a TypeScript module.
 *
 * These come from Kenney's Isometric Buildings pack, which is CC0 - public domain, no attribution
 * required - so unlike the other sheets there is no licence question hanging over them.
 *
 * They are PNG rather than vector. That is fine here and would not be fine for an animal: a tile is
 * drawn at 133px and every place the game shows a building is smaller than that, so it is only ever
 * scaled down. Nothing is ever asked to grow.
 *
 * Hand-run; the output is committed.
 *
 *   npm run building-art
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const CONFIG = 'scripts/building-art.config.json';
const OUT = 'src/components/zooGame/art/buildingArt.generated.ts';

/** A PNG's pixel size, straight out of its header - no decoder needed for the two numbers we want. */
function pngSize(bytes) {
  if (bytes.readUInt32BE(0) !== 0x89504e47) throw new Error('not a PNG');
  return { w: bytes.readUInt32BE(16), h: bytes.readUInt32BE(20) };
}

const config = JSON.parse(readFileSync(CONFIG, 'utf8'));
const entries = [];

for (const [type, spec] of Object.entries(config.buildings)) {
  const bytes = readFileSync(resolve(config.dir, spec.file));
  const { w, h } = pngSize(bytes);
  entries.push({ type, w, h, note: spec.note, data: bytes.toString('base64') });
}

entries.sort((a, b) => a.type.localeCompare(b.type));
const body = entries.map((e) => `  ${e.type}: {
    // ${e.note}
    w: ${e.w}, h: ${e.h},
    src: 'data:image/png;base64,${e.data}',
  },`).join('\n');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `/* Generated by scripts/extract-building-art.mjs - do not edit by hand.
 *
 * Artwork: ${config.credit}. Re-run \`npm run building-art\` after changing
 * scripts/building-art.config.json.
 */

export type BuildingArt = {
  /** The tile's own pixel size. Every use in the game is smaller, so it is only scaled down. */
  w: number;
  h: number;
  /** The tile itself, inline, so a scene can be screenshotted or saved without fetching anything. */
  src: string;
};

export const BUILDING_ART: Record<string, BuildingArt> = {
${body}
};
`);

const kb = Buffer.byteLength(readFileSync(OUT)) / 1024;
console.log(`${entries.length} buildings -> ${OUT} (${kb.toFixed(0)} KB)`);
for (const e of entries) console.log(`  ${e.type.padEnd(10)} ${e.w}×${e.h}  ${e.note}`);
